-- Read-only, transaction-consistent logical snapshot of this app's public data.
-- Execute in the verified project. Export the single JSON cell without editing it.
WITH exported AS (
WITH snapshot AS (
  SELECT jsonb_build_object(
    'users', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY to_jsonb(t)::text),'[]'::jsonb) FROM public.users t),
    'couple', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY to_jsonb(t)::text),'[]'::jsonb) FROM public.couple t),
    'expenses', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY to_jsonb(t)::text),'[]'::jsonb) FROM public.expenses t),
    'investment_portfolios', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY to_jsonb(t)::text),'[]'::jsonb) FROM public.investment_portfolios t),
    'investment_purchases', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY to_jsonb(t)::text),'[]'::jsonb) FROM public.investment_purchases t),
    'investment_price_snapshots', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY to_jsonb(t)::text),'[]'::jsonb) FROM public.investment_price_snapshots t),
    'couple_deposits_archivo_20261010', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY to_jsonb(t)::text),'[]'::jsonb) FROM public.couple_deposits_archivo_20261010 t),
    'expenses_respaldo_20261010', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY to_jsonb(t)::text),'[]'::jsonb) FROM public.expenses_respaldo_20261010 t),
    'user_income', (SELECT coalesce(jsonb_agg(to_jsonb(t) ORDER BY to_jsonb(t)::text),'[]'::jsonb) FROM public.user_income t)
  ) AS tables
), table_definitions AS (
  SELECT c.relname AS name,
    'CREATE TABLE public.' || quote_ident(c.relname) || E' (\n' ||
    string_agg('  ' || quote_ident(a.attname) || ' ' || format_type(a.atttypid,a.atttypmod) ||
      CASE
        WHEN a.attgenerated <> '' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin,d.adrelid) || ') STORED'
        WHEN a.attidentity = 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
        WHEN a.attidentity = 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY'
        WHEN d.oid IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(d.adbin,d.adrelid)
        ELSE ''
      END || CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END, E',\n' ORDER BY a.attnum) || E'\n);' AS ddl
  FROM pg_class c
  JOIN pg_namespace n ON n.oid=c.relnamespace
  JOIN pg_attribute a ON a.attrelid=c.oid AND a.attnum>0 AND NOT a.attisdropped
  LEFT JOIN pg_attrdef d ON d.adrelid=c.oid AND d.adnum=a.attnum
  WHERE n.nspname='public' AND c.relkind='r'
  GROUP BY c.oid,c.relname
)
SELECT jsonb_build_object(
  'format','gasto-tracker-public-backup-v1',
  'captured_at',transaction_timestamp(),
  'postgres_version',current_setting('server_version'),
  'tables',snapshot.tables,
  'table_definitions',(SELECT coalesce(jsonb_agg(jsonb_build_object('name',name,'ddl',ddl) ORDER BY name),'[]'::jsonb) FROM table_definitions),
  'constraints',(SELECT coalesce(jsonb_agg(format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;',r.relname,c.conname,pg_get_constraintdef(c.oid,true)) ORDER BY c.contype,r.relname,c.conname),'[]'::jsonb) FROM pg_constraint c JOIN pg_class r ON r.oid=c.conrelid JOIN pg_namespace n ON n.oid=r.relnamespace WHERE n.nspname='public'),
  'indexes',(SELECT coalesce(jsonb_agg(pg_get_indexdef(i.indexrelid)||';' ORDER BY r.relname),'[]'::jsonb) FROM pg_index i JOIN pg_class r ON r.oid=i.indrelid JOIN pg_namespace n ON n.oid=r.relnamespace WHERE n.nspname='public' AND NOT EXISTS(SELECT 1 FROM pg_constraint c WHERE c.conindid=i.indexrelid)),
  'functions',(SELECT coalesce(jsonb_agg(pg_get_functiondef(p.oid) ORDER BY p.proname),'[]'::jsonb) FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public' AND p.prokind IN ('f','p')),
  'sequences',(SELECT coalesce(jsonb_agg(to_jsonb(s) ORDER BY sequencename),'[]'::jsonb) FROM pg_sequences s WHERE schemaname='public'),
  'triggers',(SELECT coalesce(jsonb_agg(pg_get_triggerdef(t.oid)||';' ORDER BY t.tgname),'[]'::jsonb) FROM pg_trigger t JOIN pg_class r ON r.oid=t.tgrelid JOIN pg_namespace n ON n.oid=r.relnamespace WHERE n.nspname='public' AND NOT t.tgisinternal),
  'policies',(SELECT coalesce(jsonb_agg(to_jsonb(p) ORDER BY tablename,policyname),'[]'::jsonb) FROM pg_policies p WHERE schemaname='public'),
  'rls',(SELECT coalesce(jsonb_agg(jsonb_build_object('table',c.relname,'enabled',c.relrowsecurity,'forced',c.relforcerowsecurity) ORDER BY c.relname),'[]'::jsonb) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public' AND c.relkind='r'),
  'table_inventory',(SELECT coalesce(jsonb_agg(table_name ORDER BY table_name),'[]'::jsonb) FROM information_schema.tables WHERE table_schema='public' AND table_type='BASE TABLE')
) AS backup_json
FROM snapshot
)
-- Return text so browser JSON parsing cannot round high-precision numeric values.
SELECT backup_json::text AS backup_json, md5(backup_json::text) AS source_md5
FROM exported;
